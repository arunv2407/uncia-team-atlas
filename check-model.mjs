import fs from 'node:fs/promises';
import ts from 'typescript';
import assert from 'node:assert/strict';
const compile=async p=>'data:text/javascript;base64,'+Buffer.from(ts.transpileModule(await fs.readFile(p,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64');
const {initialNodes:nodes}=await import(await compile('app/seed.ts'));
const {validateNodes,descendants}=await import(await compile('app/model.ts'));
assert.equal(validateNodes(nodes),null);
const cng=[nodes.find(n=>n.id==='guna'),...descendants(nodes,'guna')];
assert.equal(cng.filter(n=>n.status==='Filled').reduce((a,n)=>a+n.count,0),71);
assert.equal(cng.filter(n=>n.status==='Vacant').reduce((a,n)=>a+n.count,0),12);
assert.equal(descendants(nodes,'satish').filter(n=>n.status==='Filled').length,12);
assert.equal(descendants(nodes,'satish').filter(n=>n.status==='Vacant').reduce((a,n)=>a+n.count,0),3);
assert.equal(nodes.filter(n=>n.status==='Filled').reduce((a,n)=>a+n.count,0),90);
assert.equal(nodes.filter(n=>n.pending).length,5);
assert.ok(validateNodes(nodes.map(n=>n.id==='guna'?{...n,parentId:'govind'}:n))?.includes('circular'));
assert.ok(validateNodes(nodes.filter(n=>n.id!=='sagar')));
assert.ok(validateNodes([...nodes,nodes[0]]));
assert.ok(validateNodes(nodes.map(n=>n.id==='pankaj'?{...n,count:0}:n)));
assert.ok(validateNodes(nodes.map(n=>n.id==='pankaj'?{...n,parentId:'missing'}:n)));
assert.equal(validateNodes(nodes.map(n=>n.id==='pankaj'?{...n,parentId:'bezil'}:n)),null);
console.log('Verified seed: CNG 71 filled + 12 vacancies; QA 12 filled + 3 vacancies; organisation 90 filled + 15 vacancies; five pending structures. Cycle, invalid count, duplicate, orphan and root guards passed.');
